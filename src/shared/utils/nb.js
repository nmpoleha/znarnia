const NBSP = String.fromCharCode(160)

/* Короткие слова, которые нельзя оставлять в конце строки:
   предлоги, союзы, частицы длиной 1–2 буквы и частые трёхбуквенные. */
const SHORT = /^([а-яёА-ЯЁa-zA-Z]{1,2}|или|для|что|как|при|под|над|без|про|чем|так|это|уже|обо|изо|ото|его|её|их|тем|том|той|тот|уже|ещё|все|всё)$/i

/**
 * Расставляет неразрывные пробелы в русском тексте:
 * — тире не начинает строку (клеится к предыдущему слову);
 * — короткие предлоги и союзы не остаются в конце строки;
 * — «₽», «%», «руб.» не отрываются от числа, а число не рвётся с «класс/урок».
 */
export function nb(str) {
  const parts = String(str).split(' ')
  let out = ''
  for (let i = 0; i < parts.length; i++) {
    const cur = parts[i]
    out += cur
    if (i === parts.length - 1) break
    const next = parts[i + 1]
    // тире и знак валюты/процента не должны начинать строку
    if (next === '—' || next === '–' || next === '-' || /^[₽%]/.test(next)) out += NBSP
    // короткие слова не остаются в конце строки
    else if (SHORT.test(cur)) out += NBSP
    // число не отрывается от следующего за ним слова: «5 заданий», «20 августа»
    else if (/^\d+$/.test(cur)) out += NBSP
    else out += ' '
  }
  return out
}

export default nb
